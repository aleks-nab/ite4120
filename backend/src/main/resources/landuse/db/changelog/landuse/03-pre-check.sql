/* The cadastral code is an identifier: text, never a number, in the Estonian
   format NNNNN:NNN:NNNN. client_request_id is generated by the form once per
   check, so pressing Save twice cannot create two pre-checks. */
create table landuse.pre_check (
    id                  bigint default nextval('core.seq_id') not null,
    reference_number    text not null,
    client_request_id   text not null,
    cadastral_code      text not null,
    plot_area_m2        numeric(12,2),
    planned_building    text not null,
    contact_email       text not null,
    status              text not null default 'NEW',
    officer_comment     text,
    register_complete   boolean not null,
    sys_status          char(1),
    sys_version         int,
    sys_created_at      timestamptz,
    sys_created_by      text,
    sys_modified_at     timestamptz,
    sys_modified_by     text,
    constraint pre_check_pk primary key (id),
    constraint pre_check_cadastral_code_chk check (cadastral_code ~ '^[0-9]{5}:[0-9]{3}:[0-9]{4}$'),
    constraint pre_check_plot_area_chk check (plot_area_m2 is null or plot_area_m2 > 0),
    constraint pre_check_email_chk check (contact_email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    constraint pre_check_status_chk check (status in ('NEW', 'ANSWERED')),
    constraint pre_check_answer_chk check (status <> 'ANSWERED' or officer_comment is not null)
);

select core.create_table_metadata('landuse.pre_check');

/* Unique among ACTIVE rows only, like animals.animal registry_code. */
create unique index pre_check_reference_number_ukey
    on landuse.pre_check (reference_number) where (sys_status = 'A');

create unique index pre_check_client_request_ukey
    on landuse.pre_check (client_request_id) where (sys_status = 'A');

create index pre_check_status_idx on landuse.pre_check (status) where (sys_status = 'A');
